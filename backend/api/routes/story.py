TOTAL_MIN, TOTAL_MAX = 3, 120  # matches the composer's length slider

_PLAN_SYSTEM = """You are a film director planning a short AI-generated video from a user's brief.
Split the brief into sequential scenes that together tell one continuous story.

Return ONLY a JSON object of this exact shape:
{"title": "...", "story": "...", "bible": {"characters": "...", "environment": "...", "lighting": "...", "camera": "...", "grading": "..."}, "scenes": [{"title": "...", "duration": <int>, "image_prompt": "...", "script": "...", "caption": "...", "motion": "Still" | "Push in" | "Pan left", "references": [<int>, ...]}]}

Rules:
- "title": the film's display title, 2–5 words, in the output language. Never just repeat the brief.
- Decide the number of scenes from the total duration and pacing. Each scene's "duration" is a whole number of seconds within the allowed per-scene range, and the durations MUST sum exactly to the requested total.
- "story": a concise narrative (3–6 sentences) covering the full arc.
- "bible": the LOCKED production design in English, identical for every scene: recurring characters (age, face, hair, build, wardrobe), environment, lighting, camera (lens, height, movement style), grading.
- "image_prompt": the scene's opening frame for a text-to-image model, in English. Focus on THIS scene's composition, action frozen mid-moment, framing and blocking; refer to bible entities briefly.
- "script": 1–2 sentences of voice-over narration for the scene, sized to be spoken within its duration.
- "caption": a very short on-screen caption (max 8 words), or "" when the scene needs none.
- "motion": a simple camera treatment for the edit — "Push in" for emphasis, "Pan left" for travel, else "Still".
- NO readable text inside image_prompt or the bible (AI models render text badly); convey meaning through composition and color.
- "references": the numbers of the reference images (listed below, if any) that the scene uses; [] if none. Describe a referenced character/object/location using its analysed description so it stays identical across scenes."""

_BIBLE_FIELDS = ("characters", "environment", "lighting", "camera", "grading")


def _normalize_bible(raw: Any) -> dict:
    if not isinstance(raw, dict):
        return {}
    return {k: str(raw.get(k) or "").strip() for k in _BIBLE_FIELDS if str(raw.get(k) or "").strip()}


def _fit_durations(raw: list[Any], total: int, lo: int, hi: int) -> list[int]:
    durations = []
    for d in raw:
        try:
            v = int(round(float(d)))
        except (TypeError, ValueError):
            v = lo
        durations.append(min(max(v, lo), hi))
    guard = 0
    while sum(durations) != total and guard < 400:
        guard += 1
        diff = total - sum(durations)
        if diff > 0:
            i = min(range(len(durations)), key=lambda k: durations[k])
            if durations[i] >= hi:
                break
            durations[i] += 1
        else:
            i = max(range(len(durations)), key=lambda k: durations[k])
            if durations[i] <= lo:
                break
            durations[i] -= 1
    return durations


def normalize_plan(data: dict, total: int, model_id: str, valid_refs: set[int]) -> list[dict]:
    """Coerce the LLM's scenes into clips the chosen engine can render: whole
    seconds inside the engine's duration range, summing to `total` whenever
    that is feasible."""
    options = video_model(model_id)["durations"]
    lo, hi = min(options), max(options)
    raw = [s for s in (data.get("scenes") or []) if isinstance(s, dict) and str(s.get("image_prompt") or "").strip()]
    if not raw:
        raise ValueError("The text model returned no usable scenes")
    min_n = max(1, -(-total // hi))
    max_n = max(1, total // lo)
    raw = raw[:max_n]
    while len(raw) < min_n:
        raw.append({**raw[-1], "title": f"{raw[-1].get('title') or 'Scene'} (cont.)"})
    durations = _fit_durations([s.get("duration") for s in raw], total, lo, hi) if total >= lo else [lo]
    scenes = []
    for i, s in enumerate(raw[: len(durations)]):
        refs = []
        for r in s.get("references") or []:
            try:
                n = int(r)
            except (TypeError, ValueError):
                continue
            if n in valid_refs and n not in refs:
                refs.append(n)
        motion = s.get("motion") if s.get("motion") in ("Still", "Push in", "Pan left") else "Still"
        scenes.append({
            "index": i,
            "title": str(s.get("title") or f"Scene {i + 1}").strip()[:80],
            "duration": clamp_duration(model_id, durations[i]),
            "image_prompt": str(s.get("image_prompt") or "").strip(),
            "script": str(s.get("script") or "").strip(),
            "caption": str(s.get("caption") or "").strip()[:126],
            "motion": motion,
            "reference_indices": refs,
        })
    return scenes


class ReferenceIn(BaseModel):
    index: int
    asset_id: Optional[str] = None
    url: Optional[str] = None
    analysis: Optional[Dict[str, Any]] = None


class PlanRequest(BaseModel):
    prompt: str
    total_duration: int = 20
    aspect_ratio: Optional[str] = "16:9"
    video_model: Optional[str] = None
    scene_count: Optional[int] = None
    references: Optional[List[ReferenceIn]] = None
    # Reference numbers of the video's chosen first / last frame, if any.
    first_frame: Optional[int] = None
    last_frame: Optional[int] = None
    # Flow: the scenes form one continuous shot (each clip ends where the next begins).
    flow: bool = False
    llm: Optional[str] = None
    language: Optional[str] = None
    project_id: Optional[str] = None


def plan_prompt(body: PlanRequest, total: int, options: list[int], refs: list[ReferenceIn]) -> str:
    """The user message for the planner: brief, timing, references, and the
    first/last-frame and Flow continuity rules."""
    user = (
        f"Brief:\n{body.prompt.strip()}\n\nTotal duration: exactly {total} seconds.\n"
        f"Allowed per-scene duration: {min(options)}–{max(options)} seconds.\n"
        f"Aspect ratio: {body.aspect_ratio or '16:9'}.\n"
    )
    if body.scene_count:
        user += f"Use exactly {int(body.scene_count)} scenes if the durations allow it.\n"
    if refs:
        user += "\nReference images:\n" + "\n".join(
            f"{r.index}. [{(r.analysis or {}).get('kind', 'other')}] \"{(r.analysis or {}).get('name', 'reference')}\": "
            f"{(r.analysis or {}).get('description', '')}"
            for r in refs
        ) + "\n"
    indices = {r.index for r in refs}
    if body.first_frame in indices:
        user += (f"\nThe video OPENS exactly on reference image {body.first_frame}: scene 1's image_prompt must describe "
                 f"that image's composition, subject and setting, and scene 1 lists it in \"references\".\n")
    if body.last_frame in indices:
        user += (f"\nThe video ENDS exactly on reference image {body.last_frame}: the final scene's action must arrive "
                 f"at that image's composition, and the final scene lists it in \"references\".\n")
    if body.flow:
        user += ("\nContinuity: the scenes form ONE continuous shot. Each scene continues directly from the end of the "
                 "previous one — same subject, same place, same lighting, unbroken action — so the clips join without "
                 "a visible cut. Each image_prompt is the exact moment the previous scene ends on. Use \"Still\" motion.\n")
    return user


@router.post("/story/plan", dependencies=[require_permission("resources:write")])
async def plan_story(body: PlanRequest, ctx: PluginContext = Depends(get_ctx)):
    """Plan a brief into scenes. Runs in the background; the result lands on
    an item (`gen_params`) found via GET /generations/{generation_id}."""
    idea = (body.prompt or "").strip()
    if not idea:
        raise HTTPException(status_code=400, detail="prompt is required")
    total = max(TOTAL_MIN, min(TOTAL_MAX, int(body.total_duration or 20)))
    model_id = video_model(body.video_model or "")["id"]
    options = video_model(model_id)["durations"]
    refs = [r for r in (body.references or []) if isinstance(r.analysis, dict)]
    valid_refs = {r.index for r in refs if (r.analysis or {}).get("kind") != "style"}

    user = plan_prompt(body, total, options, refs)

    org_id = ctx.organization_id
    generation_id = str(uuid.uuid4())
    bind_user_id(ctx.user_id)

    async def _bg():
        async with standalone_background_session(ctx) as db:
            doc = await create_initial_item(
                db, organization_id=org_id, user_id=ctx.user_id, type="story_plan",
                model_name=body.llm or "auto", prompt=idea, params={"total_duration": total},
                project_id=body.project_id, generation_id=generation_id,
            )
            record_id = doc["id"]
            await broadcast_event(org_id, "started", doc, record_id, ctx.user_id)
            try:
                data = await llm_json(ctx, _PLAN_SYSTEM, user, body.llm, language=body.language)
                scenes = normalize_plan(data, total, model_id, valid_refs)
                by_index = {r.index: r for r in refs}
                for s in scenes:
                    s["reference_asset_ids"] = [by_index[i].asset_id for i in s["reference_indices"] if by_index[i].asset_id]
                result = {
                    "title": str(data.get("title") or "").strip()[:80],
                    "story": str(data.get("story") or "").strip(),
                    "bible": _normalize_bible(data.get("bible")),
                    "total_duration": sum(s["duration"] for s in scenes),
                    "video_model": model_id,
                    "scenes": scenes,
                }
                await set_item_fields(db, record_id, {"gen_params": result})
                final = await update_item_success(db, record_id, url="story-plan")
                await broadcast_event(org_id, "completed", final, record_id, ctx.user_id)
            except Exception as e:  # noqa: BLE001 — surfaced on the item
                logger.exception("story plan failed")
                mark_failed(getattr(e, "detail", None) or str(e))
                failed = await update_item_failed(db, record_id, getattr(e, "detail", None) or str(e))
                await broadcast_event(org_id, "failed", failed, record_id, ctx.user_id)

    asyncio.create_task(run_task("story_plan", _bg(), project_id=generation_id))
    return {"status": "pending", "generation_id": generation_id}


_VIDEO_PROMPT_SYSTEM = """You write motion prompts for image-to-video AI models (Kling, Seedance).
Each scene of a short film already has a start frame; your prompt animates it.

Return ONLY a JSON object of this exact shape:
{"scenes": [{"index": <int>, "video_prompt": "..."}]}

Rules:
- One video_prompt per input scene, keyed by the scene's index.
- Describe motion and change over time: the subject's action, camera movement, pacing that fits the scene's duration, atmosphere.
- The start frame fixes the scene's appearance — focus on what MOVES.
- Keep continuity between consecutive scenes so the clips cut together as one film.
- Never ask for on-screen text of any kind.
- Write in English."""

_AUDIO_RULE = "\n- AUDIO: the clip renders audio from this prompt — weave ambient sound, foley and mood cues into the action description."
_SILENT_RULE = "\n- AUDIO: the clip is silent — keep the prompt purely visual."


class PromptScene(BaseModel):
    index: int
    title: Optional[str] = ""
    duration: float = 5
    image_prompt: str = ""
    camera: Optional[str] = None


class VideoPromptsRequest(BaseModel):
    story: Optional[str] = ""
    prompt: Optional[str] = ""
    bible: Optional[Dict[str, Any]] = None
    video_model: Optional[str] = None
    audio: bool = True
    scenes: List[PromptScene]
    llm: Optional[str] = None


@router.post("/story/video-prompts", dependencies=[require_permission("resources:write")])
async def video_prompts(body: VideoPromptsRequest, ctx: PluginContext = Depends(get_ctx)):
    if not body.scenes:
        raise HTTPException(status_code=400, detail="scenes are required")
    model = video_model(body.video_model or "")
    system = _VIDEO_PROMPT_SYSTEM + (_AUDIO_RULE if body.audio and model["audio"] else _SILENT_RULE)
    bible = _normalize_bible(body.bible)
    lines = [
        f"Scene {s.index} — \"{s.title or ''}\" ({round(s.duration)}s): {s.image_prompt}"
        + (f" Camera: {s.camera}." if s.camera else "")
        for s in body.scenes
    ]
    user = (
        (f"Brief:\n{body.prompt}\n\n" if (body.prompt or "").strip() else "")
        + (f"Story:\n{body.story}\n\n" if (body.story or "").strip() else "")
        + ("Locked production design:\n" + "\n".join(f"- {k}: {v}" for k, v in bible.items()) + "\n\n" if bible else "")
        + "Scenes:\n" + "\n".join(lines)
    )
    try:
        data = await llm_json(ctx, system, user, body.llm)
    except HTTPException:
        data = {}
    by_index: dict[int, str] = {}
    for s in data.get("scenes") or []:
        try:
            idx = int(s.get("index"))
        except (TypeError, ValueError, AttributeError):
            continue
        vp = str(s.get("video_prompt") or "").strip()
        if vp:
            by_index[idx] = vp
    return {
        "scenes": [
            {"index": s.index, "video_prompt": by_index.get(s.index)
             or f"{s.image_prompt} — cinematic camera movement, natural motion"}
            for s in body.scenes
        ]
    }
